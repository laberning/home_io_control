/// @file corpus_stopped_off_target_test.cpp
/// @brief Real covers that come to rest off their target, through the hub's status path.
///
/// Two VELUX SSL solar roller shutters stop 119 and 171 raw short of an end target with the
/// STOPPED flag set (issue #151), and a Somfy bioclimatic pergola 378-479 raw off an intermediate
/// one (PR #157). Each must read moving for exactly one more tracked poll and then at rest, so the
/// cover goes idle and polling ends, instead of staying OPENING/CLOSING.

#include "corpus_generated.h"
#include "hub_core.h"
#include "hub_internal.h"
#include "proto_frame.h"

#include "test_helpers.h"

#include <gtest/gtest.h>

#include <string>

using namespace esphome::home_io_control;
using test::TestableHubComponent;

namespace {

/// Parse one capture frame from its generated byte array (these captures carry no CRC).
template<size_t N> IoFrame frame_of(const uint8_t (&bytes)[N]) {
  IoFrame frame;
  EXPECT_TRUE(parse(bytes, static_cast<uint8_t>(N), frame));
  EXPECT_EQ(frame.cmd, CMD_PRIVATE_RESP);
  return frame;
}

/// A hub with one registered device that a tracked poll chain is following (as after a command).
struct TrackedDevice {
  esphome::test_clock::ManualClock clock{50000};
  TestableHubComponent comp;
  std::string id;

  explicit TrackedDevice(const char *device_id) : id(device_id) {
    comp.add_device(id);
    comp.begin_status_poll_tracking_(id, 0);
  }

  IoDevice &dev() { return *comp.get_device(id); }
  bool tracking() { return comp.poll_policy_.is_tracking_active(id, esphome::millis()); }

  /// Apply one reply as the answer to a status poll, `gap_ms` after the previous one.
  void reply(const IoFrame &frame, uint32_t gap_ms) {
    esphome::test_clock::advance_ms(gap_ms);
    comp.update_device_status_(frame);
  }
};

}  // namespace

TEST(CorpusStoppedOffTarget, SslRestingShortOfOpenSettlesThenIsAtRest) {
  using namespace corpus;
  TrackedDevice t("F06E93");
  const IoFrame first = frame_of(velux_ssl_statuspoll_stopped_off_target_frame0_bytes);
  const IoFrame again = frame_of(velux_ssl_statuspoll_stopped_off_target_frame2_bytes);

  t.reply(first, 0);
  EXPECT_FALSE(t.dev().is_stopped) << "0x0000 / 0x0077 stopped: one more poll first";
  EXPECT_TRUE(t.tracking());
  EXPECT_EQ(t.dev().last_moving_evidence_ms, 0u) << "the confirming poll leads with the wake-up preamble";

  t.reply(again, 10081);
  EXPECT_TRUE(t.dev().is_stopped) << "same reply again: at rest 119 raw short of open";
  EXPECT_FALSE(t.tracking()) << "polling ends instead of running for the whole tracking window";
}

TEST(CorpusStoppedOffTarget, SslLandingExactlyOnTargetIsAtRestAtOnce) {
  using namespace corpus;
  TrackedDevice t("FFD95B");

  t.reply(frame_of(velux_ssl_statuspoll_stopped_off_target_frame1_bytes), 0);
  EXPECT_FALSE(t.dev().is_stopped) << "frame 1 is the shutter still travelling";
  EXPECT_FALSE(t.dev().stop_candidate.armed());

  t.reply(frame_of(velux_ssl_statuspoll_stopped_off_target_frame3_bytes), 9472);
  EXPECT_TRUE(t.dev().is_stopped) << "0x0000 / 0x0000 stopped needs no confirmation";
  EXPECT_FALSE(t.tracking());
}

TEST(CorpusStoppedOffTarget, SslRestingShortOfClosedSettlesThenIsAtRest) {
  using namespace corpus;
  TrackedDevice t("FFD95B");

  t.reply(frame_of(velux_ssl_statuspoll_stopped_off_target_frame4_bytes), 0);
  EXPECT_FALSE(t.dev().is_stopped) << "0xC800 / 0xC755 stopped: one more poll first";
  EXPECT_TRUE(t.tracking());

  t.reply(frame_of(velux_ssl_statuspoll_stopped_off_target_frame5_bytes), 9001);
  EXPECT_TRUE(t.dev().is_stopped) << "at rest 171 raw short of closed";
  EXPECT_FALSE(t.tracking());
}

TEST(CorpusStoppedOffTarget, PergolaRestingOffAnIntermediateTargetSettlesThenIsAtRest) {
  using namespace corpus;
  // The capture holds each of these replies once; the repeat a confirming poll would draw is the
  // same frame sent again.
  for (const IoFrame &frame : {frame_of(somfy_pergola_louver_statuspoll_replies_sx1262_frame2_bytes),
                               frame_of(somfy_pergola_louver_statuspoll_replies_sx1262_frame3_bytes)}) {
    TrackedDevice t("262552");
    t.reply(frame, 0);
    EXPECT_FALSE(t.dev().is_stopped) << "70 % / 70.9 % and 50 % / 50.7 % stopped: one more poll first";
    t.reply(frame, 3000);
    EXPECT_TRUE(t.dev().is_stopped) << "the repeated report confirms it";
    EXPECT_FALSE(t.tracking());
  }
}
