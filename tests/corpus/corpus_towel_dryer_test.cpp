/// @file corpus_towel_dryer_test.cpp
/// @brief The towel-dryer registers of the heater codec (proto_heating.h) and the TOWEL_DRYER heating
/// profile (proto_heating_profiles.h) against real replies from two Atlantic Adelis towel dryers
/// (issue #202).
///
/// Only the replies were logged, so these captures pin the decoders and the profile's mapping, not
/// the requests or the exchange. The reporter read the display in the same session, which is what each
/// expectation below compares with.

#include "corpus_generated.h"
#include "hub_decisions.h"
#include "proto_frame.h"
#include "proto_heating.h"
#include "proto_heating_profiles.h"

#include <gtest/gtest.h>

#include <cmath>
#include <string>

using namespace esphome::home_io_control;

namespace {

/// Parse one capture frame from its generated byte array (these captures carry no CRC).
template<size_t N> IoFrame frame_of(const uint8_t (&bytes)[N]) {
  IoFrame frame{};
  EXPECT_TRUE(parse(bytes, static_cast<uint8_t>(N), frame));
  return frame;
}

/// Decode a register reply, failing the test when it carries no value.
template<size_t N> float value_of(const uint8_t (&bytes)[N], HeatingFunction fn) {
  float value = NAN;
  EXPECT_TRUE(decode_heating_reply(frame_of(bytes), fn, value)) << heating_function_name(fn);
  return value;
}

const HeatingProfile &towel_profile() {
  return *find_heating_profile(DeviceType::ELECTRICAL_HEATER, 1, DeviceModel::TOWEL_DRYER);
}

/// The HVAC mode the towel-dryer profile shows for a captured reply of register 0x0136.
template<size_t N> HeatingHvacMode shown_mode(const uint8_t (&bytes)[N]) {
  const auto wire = static_cast<uint8_t>(value_of(bytes, HeatingFunction::TOWEL_MODE));
  const HeatingObservedState *state = find_observed_state(towel_profile(), wire);
  EXPECT_NE(state, nullptr) << "mode value " << static_cast<unsigned>(wire);
  return state != nullptr ? state->hvac : HeatingHvacMode::OFF;
}

/// The preset the towel-dryer profile shows for a captured reply of register 0x013E.
template<size_t N> HeatingPresetEntry shown_preset(const uint8_t (&bytes)[N]) {
  const HeatingProfile &profile = towel_profile();
  const auto wire = static_cast<uint8_t>(value_of(bytes, HeatingFunction::TEMPORARY_STATE));
  const HeatingObservedState *state = find_observed_preset(profile, wire);
  EXPECT_NE(state, nullptr) << "temporary state " << static_cast<unsigned>(wire);
  return state != nullptr ? profile.presets[state->preset] : profile.presets[0];
}

}  // namespace

TEST(CorpusTowelDryer, EachDisplayedModeIsTheModeTheCardShows) {
  EXPECT_EQ(shown_mode(corpus::atlantic_adelis_probe_mode_reads_frame0_bytes), HeatingHvacMode::HEAT) << "MANUEL";
  EXPECT_EQ(shown_mode(corpus::atlantic_adelis_probe_mode_reads_frame2_bytes), HeatingHvacMode::AUTO)
      << "PROG, comfort period";
  EXPECT_EQ(shown_mode(corpus::atlantic_adelis_probe_mode_reads_frame4_bytes), HeatingHvacMode::AUTO)
      << "PROG, eco period";
  EXPECT_EQ(shown_mode(corpus::atlantic_adelis_probe_mode_reads_frame6_bytes), HeatingHvacMode::OFF) << "off";
}

TEST(CorpusTowelDryer, TheRadiatorModeRegisterReadsOffAsFourNotZero) {
  // Register 0x0100 follows the display too, but its off is 4: the profile reads 0x0136, never 0x0100.
  EXPECT_FLOAT_EQ(value_of(corpus::atlantic_adelis_probe_mode_reads_frame1_bytes, HeatingFunction::SET_MODE), 3.0F);
  EXPECT_FLOAT_EQ(value_of(corpus::atlantic_adelis_probe_mode_reads_frame3_bytes, HeatingFunction::SET_MODE), 2.0F);
  EXPECT_FLOAT_EQ(value_of(corpus::atlantic_adelis_probe_mode_reads_frame7_bytes, HeatingFunction::SET_MODE),
                  static_cast<float>(HeatingMode::OFF));
  EXPECT_EQ(towel_profile().mode_fn, HeatingFunction::TOWEL_MODE);
}

TEST(CorpusTowelDryer, BoostAndDryingShowAsTheirPresetsAndTheElementHeats) {
  // First unit (BB0B50) in boost; second unit (BD684B) drying.
  const HeatingPresetEntry boost = shown_preset(corpus::atlantic_adelis_probe_register_01_sweep_frame30_bytes);
  EXPECT_EQ(boost.id, HeatingPresetId::BOOST);
  const HeatingPresetEntry drying = shown_preset(corpus::atlantic_adelis_probe_register_01_sweep_drying_frame62_bytes);
  ASSERT_EQ(drying.id, HeatingPresetId::CUSTOM);
  EXPECT_STREQ(drying.custom_name, "Drying");

  EXPECT_FLOAT_EQ(
      value_of(corpus::atlantic_adelis_probe_register_01_sweep_frame70_bytes, HeatingFunction::WORKING_RATE), 100.0F);
  EXPECT_FLOAT_EQ(
      value_of(corpus::atlantic_adelis_probe_register_01_sweep_drying_frame38_bytes, HeatingFunction::WORKING_RATE),
      100.0F);
  EXPECT_FLOAT_EQ(
      value_of(corpus::atlantic_adelis_probe_register_01_sweep_drying_frame23_bytes, HeatingFunction::REGULATOR_STATE),
      0.0F)
      << "the regulator reads 'none' while the element runs: the action comes from the working rate";
  EXPECT_EQ(towel_profile().action_source, HeatingActionSource::WORKING_RATE);
}

TEST(CorpusTowelDryer, DryingLeavesTheBaseModeAndThePolledTemperaturesReadable) {
  EXPECT_EQ(shown_mode(corpus::atlantic_adelis_probe_register_01_sweep_drying_frame54_bytes), HeatingHvacMode::HEAT);
  EXPECT_FLOAT_EQ(
      value_of(corpus::atlantic_adelis_probe_register_01_sweep_drying_frame21_bytes, HeatingFunction::ROOM_TEMPERATURE),
      19.75F);
  const float setpoint =
      value_of(corpus::atlantic_adelis_probe_register_01_sweep_drying_frame3_bytes, HeatingFunction::SET_TEMPERATURE);
  EXPECT_FLOAT_EQ(setpoint, 19.0F);
  EXPECT_FLOAT_EQ(value_of(corpus::atlantic_adelis_probe_register_01_sweep_drying_frame56_bytes,
                           HeatingFunction::TOWEL_COMFORT_SETPOINT),
                  setpoint)
      << "0x0138 holds the same comfort setpoint as 0x0103";
  EXPECT_FLOAT_EQ(
      value_of(corpus::atlantic_adelis_probe_register_01_sweep_drying_frame2_bytes, HeatingFunction::MAX_SETPOINT),
      28.0F);
}

TEST(CorpusTowelDryer, TheModelNameRegisterLogsAsOneLine) {
  for (const IoFrame &reply : {frame_of(corpus::atlantic_adelis_probe_register_01_sweep_frame57_bytes),
                               frame_of(corpus::atlantic_adelis_probe_register_01_sweep_drying_frame25_bytes)}) {
    ASSERT_TRUE(heating_reply_echoes_register(reply, HEATING_REGISTER_HIGH_BYTE, HEATING_REGISTER_MODEL_NAME));
    EXPECT_EQ(decisions::format_heater_model_name(reply.data + HEATING_REPLY_VALUE_OFFSET,
                                                  reply.data_len - HEATING_REPLY_VALUE_OFFSET),
              "ADELIS 2 DIGIT");
  }
}

TEST(CorpusTowelDryer, AnAbsentRegisterIsAnEchoWithoutAValue) {
  // 0x0135 is answered with the header alone: the "empty" the model check tells apart from a value.
  const IoFrame empty = frame_of(corpus::atlantic_adelis_probe_register_01_sweep_drying_frame53_bytes);
  EXPECT_TRUE(heating_reply_echoes_register(empty, HEATING_REGISTER_HIGH_BYTE, 0x35));
  EXPECT_EQ(empty.data_len, HEATING_REPLY_VALUE_OFFSET);
  const IoFrame mode = frame_of(corpus::atlantic_adelis_probe_register_01_sweep_drying_frame54_bytes);
  EXPECT_GT(mode.data_len, HEATING_REPLY_VALUE_OFFSET) << "0x0136 answers with a value on a towel dryer";
}
